"""The distances d={d1, d2, ....dn} are manage as a mixture of two Gaussian distributions:

 >p(d)= π1 ​N(d ; μ1 ​, σ12 ​) + π2 ​N( d ; μ2 ​, σ22​)

- μi -> is the mean
- σi -> is the standard deviation
- πi -> is the mixture weight
- π1+π 2 =1.

The Gaussian density is the classical Normal probability distribution formula

Ordering μ1​<μ2​  allow to set ad first G. D. the ID and the second one OOD

Threshold set when the two G. D. are equales
> π1 ​N( x ; μ1 ​, σ12 ​) = π2 ​N( x ; μ2​ , σ22 ​)

The threshold is obtained by solving this equation above. The valid solution is the intersection point located between the two Gaussian means (μ 1<x<μ2	​).

If the two Gaussians have (approximately) equal variances (σ12≈σ22​), the quadratic equation simplifies to a linear equation.

The solution point is the intersection of the two weighted Gaussian distributions after the linear amplification assumption.

Otsu's threshold makes no Gaussian assumption. It searches over all possible thresholds and selects the one that maximizes the between-class variance (or equivalently minimizes the within-class variance) of the distances histogram.
"""

def gmm_threshold(d, percentile=0.95 ): #GaussianMixture fit with distances into a buffer and find out the point of division
    gmm=GaussianMixture(n_components=2,random_state=42).fit(d.reshape(-1,1))
    mu,sig,pi=gmm.means_.ravel(),np.sqrt(gmm.covariances_).ravel(),gmm.weights_.ravel()
    o=np.argsort(mu)
    mu1,mu2,s1,s2,p1,p2=mu[o[0]],mu[o[1]],sig[o[0]],sig[o[1]],pi[o[0]],pi[o[1]]
    ## resolution of the equation,
    a=1/(2*s1**2)-1/(2*s2**2)
    b=-mu1/s1**2+mu2/s2**2
    c=mu1**2/(2*s1**2)-mu2**2/(2*s2**2)+np.log((s1*p2)/(s2*p1))
    roots=[-c/b] if abs(a)<1e-12 and abs(b)>1e-12 else []
    if abs(a)>=1e-12:
        disc=b*b-4*a*c
        if disc>=0: roots=[(-b-np.sqrt(disc))/(2*a),(-b+np.sqrt(disc))/(2*a)]

    th=next((r for r in roots if mu1<r<mu2),None)  #distance < th  --> ID distance > th  --> OOD
    upper = norm.ppf(percentile, loc=mu1, scale=s1)
    #return th,(mu1,s1),(mu2,s2)
    return th, upper

