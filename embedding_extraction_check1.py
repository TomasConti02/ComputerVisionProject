def compute_auprc_and_fpr95(y_true, y_scores):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))
    """
    small recap recall=TP/(TP+FN) ->  how many OOD the system can detect over the possible amout of OOD
    precision=TP/(TP+FP) -> how often the detector that predict OOD have right
    what realy change bases on the data stream are the distances distributions
    The Precision-Recall curve is obtained by varying the decision threshold over the predicted OOD scores (centroid distances). For each threshold, Precision and Recall are computed.
    AUPRC (Area Under the Precision-Recall Curve) summarizes the detector's performance across all possible thresholds. A high AUPRC indicates that
    the centroid-distance score is effective at distinguishing OOD samples from ID samples while maintaining high precision as recall increases.
    """
    prec, rec, _ = precision_recall_curve(y_true, y_scores)
    # auprc_val is the area, if it is higher means that centroid distance as score to detect OOD is good
    auprc_val = auc(
        rec, prec
    )  # higher is better, it is the area under the precision and recall curve
    ax1.plot(rec, prec, color="b", lw=2, label=f"AUPRC = {auprc_val:.4f}")
    ax1.fill_between(rec, prec, alpha=0.2, color="b")
    ax1.set_title(
        "Precision-Recall Curve (OOD)", fontsize=12, fontweight="bold"
    )
    ax1.set_xlabel("Recall (TPR)")
    ax1.set_ylabel("Precision")
    ax1.set_xlim([0.0, 1.0])
    ax1.set_ylim([0.0, 1.05])
    ax1.grid(True, linestyle="--", alpha=0.6)
    ax1.legend(loc="lower left")
    ax2.axhline(
        y=0.95,
        color="red",
        linestyle=":",
        linewidth=1.5,
        label="Target TPR (95%)",
    )
    ############################################################################################################################################################################################################################
    """
    FPR@95TPR is a standard OOD detection metric. It measures the False Positive Rate when the detector achieves at least a 95% True Positive Rate (Recall).
    In other words, once the detector is configured to correctly identify 95% of all OOD samples, FPR@95TPR tells us what fraction of ID samples are mistakenly flagged as OOD.
    Lower values indicate a better detector because fewer ID samples are  incorrectly rejected while maintaining a very high OOD detection rate.
    """
    fpr, tpr, _ = roc_curve(y_true, y_scores, pos_label=1)  #
    # Threshold that allows the detector to correctly identify at least 5% of the OOD samples.
    idx = np.where(tpr >= 0.95)[0]
    if len(idx) > 0:
        fpr_95 = fpr[idx[0]]  # lower is better
    else:
        fpr_95 = 1.0  # fall back
    ax2.plot(fpr, tpr, color="darkorange", lw=2, label="Curva ROC")
    ax2.plot([0, 1], [0, 1], color="navy", lw=1, linestyle="--", label="Random")
    if len(idx) > 0:
        ax2.plot(
            fpr_95,
            0.95,
            "ro",
            markersize=8,
            label=f"FPR@95 = {fpr_95:.4f}",
        )
        ax2.vlines(
            x=fpr_95,
            ymin=0,
            ymax=0.95,
            colors="red",
            linestyles=":",
            linewidth=1.5,
        )
    ax2.set_title("ROC Curve & FPR@95", fontsize=12, fontweight="bold")
    ax2.set_xlabel("False Positive Rate (FPR)")
    ax2.set_ylabel("True Positive Rate (TPR / Recall)")
    ax2.set_xlim([0.0, 1.0])
    ax2.set_ylim([0.0, 1.05])
    ax2.grid(True, linestyle="--", alpha=0.6)
    ax2.legend(loc="lower right")
    plt.tight_layout()
    plt.show()
    return float(auprc_val), float(fpr_95)

