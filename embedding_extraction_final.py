def plot_confusion_matrix(y_true, y_pred, title, ax, fp_correct, fp_wrong):
    #ConfusionMatrixDisplay.from_predictions(y_true, y_pred, ax=ax, cmap='Blues')
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=["ID", "OOD"])
    disp.plot(ax=ax, cmap='Blues')
    total=cm.sum() # all data sample managed
    OOD_predicted=cm[:,1].sum() #all the item in the row with label 1 = OOD
    traffic_blocked = 100 - ( (OOD_predicted/total) *100)
    traffic_allowed = (OOD_predicted/total)*100
    total_fp = fp_correct + fp_wrong
    fp_correct_pct=-1
    fp_wrong_pct=-1
    if total_fp > 0:
      fp_correct_pct = (fp_correct / total_fp) * 100
      fp_wrong_pct = (fp_wrong / total_fp) * 100
    ax.set_title(title)
    print(f"\n OOD_predicted--> {OOD_predicted} \n traffic_allowed: {traffic_allowed:.2f} ----- {traffic_blocked:.2f}")
    return traffic_allowed, traffic_blocked, fp_correct_pct, fp_wrong_pct


def plot_temporal(time, dist, thresh, pred, true, title, ax1, ax2, ax3):
    ax1.plot(time, dist, 'b.', alpha=0.3, label='Distance')
    ax1.plot(time, thresh, 'r-', lw=2, label='Dynamic Threshold')
    ax1.axhline(y=initial_threshold, color='orange', linestyle='--', lw=3, label=f'Initial Thresh ({initial_threshold:.2f})')
    anom_idx = np.where(pred == 1)[0]
    if len(anom_idx) > 0:
        ax1.scatter(anom_idx, dist[anom_idx], color='red', s=50, marker='^', label='OOD detected')
    true_idx = np.where(true == 1)[0]
    if len(true_idx) > 0:
        ax1.scatter(true_idx, dist[true_idx], color='green', s=30, marker='o', facecolors='none', label='Ground truth OOD')
    ax1.legend(loc='upper right')
    ax1.set_title(title)
    ax1.set_ylabel('Distance')
    ax1.grid(alpha=0.3)
    ax2.plot(time, thresh, 'g-', lw=2, label='Dynamic Threshold')
