def compute_auprc_and_fpr95(y_true, y_scores):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))
    prec, rec, _ = precision_recall_curve(y_true, y_scores)
    auprc_val = auc( rec, prec)  # higher is better, it is the area under the precision and recall curve
    ax1.plot(rec, prec, color="b", lw=2, label=f"AUPRC = {auprc_val:.4f}")
    ax1.fill_between(rec, prec, alpha=0.2, color="b")
    ax1.set_title(
        "Precision-Recall Curve (OOD)", fontsize=12, fontweight="bold"
    )
    ax1.set_xlabel("Recall (TPR)")
    ax1.set_ylabel("Precision")
    ax1.set_xlim([0.0, 1.0])
    ax1.set_ylim([0.0, 1.05])
    ax1.grid(True, linestyle="--", alpha=0.6)
    ax1.legend(loc="lower left")
    ax2.axhline(
        y=0.95,
        color="red",
        linestyle=":",
        linewidth=1.5,
        label="Target TPR (95%)",
    )
    ############################################################################################################################################################################################################################
    fpr, tpr, _ = roc_curve(y_true, y_scores, pos_label=1)  #
    # Threshold that allows the detector to correctly identify at least 5% of the OOD samples.
    idx = np.where(tpr >= 0.95)[0]
    if len(idx) > 0:
        fpr_95 = fpr[idx[0]]  # lower is better
    else:
        fpr_95 = 1.0  # fall back
    ax2.plot(fpr, tpr, color="darkorange", lw=2, label="Curva ROC")
    ax2.plot([0, 1], [0, 1], color="navy", lw=1, linestyle="--", label="Random")
    if len(idx) > 0:
        ax2.plot(
            fpr_95,
            0.95,
            "ro",
            markersize=8,
            label=f"FPR@95 = {fpr_95:.4f}",
        )
        ax2.vlines(
            x=fpr_95,
            ymin=0,
            ymax=0.95,
            colors="red",
            linestyles=":",
            linewidth=1.5,
        )
    ax2.set_title("ROC Curve & FPR@95", fontsize=12, fontweight="bold")
    ax2.set_xlabel("False Positive Rate (FPR)")
    ax2.set_ylabel("True Positive Rate (TPR / Recall)")
    ax2.set_xlim([0.0, 1.0])
    ax2.set_ylim([0.0, 1.05])
    ax2.grid(True, linestyle="--", alpha=0.6)
    ax2.legend(loc="lower right")
    plt.tight_layout()
    plt.show()
    return float(auprc_val), float(fpr_95)

def start_test_phase(stream_data,stream_labels,stream_quality,detector_params,nome_test,val_dists, warm_up_limit, n_correct_id, n_wrong_id ):# labels 0 = ID 1 = OOD
    if isinstance( stream_labels[0], (str, np.str_)): #labels chack
        print(f"\n string labels input, convert to int data type")
        stream_labels = np.array(    [ 0 if lab == 'Test' else 1 for lab in stream_labels ]  )
    else:
        print(f"\n all int data types")
        stream_labels = np.array(stream_labels, dtype=int)
    stream_quality = np.array(stream_quality, dtype=int) # -1 for OOD, 0 for ID correct and 1 for ID wrong
    detector =RealTimeOODDetector(**detector_params)
    for d in val_dists[:warm_up_limit]:
        detector.distance_buffer.append(d)

    for emb, lab, qual in zip(stream_data, stream_labels, stream_quality):
      if lab == 0:  # ID
        is_correct = (qual == 0)
      elif lab == 1:  # OOD
        is_correct = None
      else:
        print(f"ERROR: label {lab} non riconosciuta!")
        is_correct = None
      detector.process(emb, true_label=int(lab), is_correct=is_correct)
    ########################################################################
    hist = detector.history
    time_steps = np.array(hist['time'])
    distances = np.array(hist['distances'])
    thresholds = np.array(hist['thresholds'])
    predictions = np.array(hist['predictions'])
    ground_truth = np.array(hist['ground_truth'])
    ########################################################################
    trend = np.array(hist['trend'])
    reset_down_count = (trend == "RESET_DOWN").sum()
    reset_up_count = (trend == "RESET_UP").sum()
    reset_same_count = (trend == "SAME").sum()
    reset_safe_count = (trend == "RESET_SAFE").sum()
    print(f"RESET_DOWN count: {reset_down_count}")
    print(f"RESET_UP count: {reset_up_count}")
    print(f"SAME count: {reset_same_count}")
    print(f"RESET_SAFE count: {reset_safe_count}")
    ########################################################################
    time_steps = time_steps[warm_up_limit:]
    distances = distances[warm_up_limit:]
    thresholds = thresholds[warm_up_limit:]
    predictions = predictions[warm_up_limit:]
    ground_truth = ground_truth[warm_up_limit:]
    ########################################################################
    valid = ~np.isnan(thresholds) # cleaning mask
    #######################################################################
    time_valid = time_steps[valid]
    dist_valid = distances[valid]
    th_valid = thresholds[valid]
    pred_valid = predictions[valid]
    true_valid = ground_truth[valid].astype(int)
    ######################################################################
    auprc_val, fpr95_val = compute_auprc_and_fpr95(true_valid, dist_valid) #based on the random data traffic define for each sample the detected distance from the closest centroids
    ######################################################################
    if np.sum(pred_valid) == 0:
        print("\n ERROR: there was no OOD!")
        acc = accuracy_score(true_valid, pred_valid)
        prec = rec = f1 = 0.0
    else:
        acc = accuracy_score(true_valid, pred_valid) #sample with a correctly prediction
        prec = precision_score(true_valid, pred_valid, pos_label=1, zero_division=0) #how often the detector that predict OOD have right
        rec = recall_score(true_valid, pred_valid, pos_label=1, zero_division=0) #how many OOD the system can detect
        f1 = f1_score(true_valid, pred_valid, pos_label=1, zero_division=0) #armonic mean between accuracy and precision

    print("\n" + "="*60)
    print(f" TEST: {nome_test}")
    print("="*60)
    print(f"Accuracy: {acc:.4f} | Precision: {prec:.4f} | Recall: {rec:.4f} | F1: {f1:.4f}")
    print(f"AUPRC: {auprc_val:.4f} | FPR@95: {fpr95_val*100:.2f}%")

    classification_report(true_valid, pred_valid, labels=[0, 1], target_names=['ID', 'OOD'], zero_division=0)
    fig, (ax1, ax2, ax3) = plt.subplots(3, 1, figsize=(14, 12), sharex=True)
    plot_temporal(time_valid, dist_valid, th_valid, pred_valid, true_valid, f"{nome_test} - Acc={acc:.3f}, F1={f1:.3f}", ax1, ax2, ax3)
    plt.tight_layout()
    plt.show()

    fig2, ax = plt.subplots(figsize=(6, 5))
    traffic_allowed, traffic_blocked, fp_correct_pct, fp_wrong_pct = ( plot_confusion_matrix( true_valid,  pred_valid, f"Confusion Matrix - {nome_test}", ax, detector.fp_correct, detector.fp_wrong, ))
    plt.tight_layout()
    plt.show()
    # im not using any more fp_correct_pct, fp_wrong_pct because are not coming from balance distributions
    #######################################################################################################################################################
    ###################################### the distribution is unbalance here ############################################################################
    #n_correct_id -> are the right id prediction into the entire data stream
    #n_wrong_id -> are the wrong id prediction into the entire data stream
    fpr_correct_total = (detector.fp_correct / n_correct_id * 100) if n_correct_id > 0 else 0.0 # n_correct_id is the ID correclty classify by the model into the data stream and detector.fp_correct is the detected
    fpr_wrong_total = (detector.fp_wrong / n_wrong_id * 100) if n_wrong_id > 0 else 0.0 # n_correct_id is the ID wrongly classify by the model into the data stream and detector.fp_wrong is the detected
    #######################################################################################################################################################
    return { 'acc': acc,  'prec': prec,  'rec': rec, 'f1': f1,  'TB': traffic_blocked, 'TA': traffic_allowed,'auprc': auprc_val, 'fpr95': fpr95_val, 'fp_correct_pct': fpr_correct_total, 'fp_wrong_pct':fpr_wrong_total  }

